#!/usr/bin/env python3
"""
scripts/dev/gen-service-token.py
================================
Generate the LOCAL-DEV internal-auth material for the podman-compose stack.

The EI-ADS engines and Ensemble Scorer validate a GCKey Bearer against a JWKS
endpoint on every request (Req 19.7). There is no GCKey IdP in a local compose
stack, so this script mints the equivalent seam the integration tests use, but
for a running stack:

  * an ephemeral RSA keypair;
  * a JWKS document (public key) written to `scripts/dev/jwks/jwks.json`, served
    by the `jwks` container at `http://jwks:80/.well-known/jwks.json` — the value
    every engine/scorer receives as `GCKEY_JWKS_URL`;
  * a long-lived (default 24 h) RS256 service JWT carrying the INVESTIGATOR role,
    written to `.env.dev-token` as both `ORCHESTRATOR_SERVICE_TOKEN=...` (the
    orchestrator presents it on internal engine/scorer calls) and
    `SERVICE_TOKEN=...` (the History Inconsistency + Regional Analysis engines
    present it on their internal CRA / Stats Canada / Job Bank adapter calls),
    which podman-compose loads.

This is faithful to Req 19.7 — the engines run their REAL `shared.auth` JWKS
validation; nothing is bypassed. The material is LOCAL DEV ONLY and never
committed: `.env.dev-token` and `scripts/dev/jwks/` are gitignored. Regenerate
before `podman-compose up`:

    python scripts/dev/gen-service-token.py

Requires `cryptography` and `python-jose` (present in .venv-core / .venv-itest).
"""

from __future__ import annotations

import base64
import json
import os
import time
import uuid

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from jose import jwt

_KID = "ei-ads-local-dev"
_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
_JWKS_DIR = os.path.join(_HERE, "jwks", ".well-known")
_JWKS_PATH = os.path.join(_JWKS_DIR, "jwks.json")
# The signing private key is persisted (gitignored) so scripts/dev/mint-token.py
# can mint ADDITIONAL-role tokens (e.g. a CLAIMANT to submit a claim) that
# validate against the SAME JWKS the running stack serves.
_KEY_PATH = os.path.join(_HERE, "jwks", "signing-key.pem")
_ENV_PATH = os.path.join(_REPO_ROOT, ".env.dev-token")
_TTL_SECONDS = int(os.environ.get("DEV_TOKEN_TTL_SECONDS", str(24 * 60 * 60)))


def _b64url_uint(value: int) -> str:
    length = (value.bit_length() + 7) // 8
    return base64.urlsafe_b64encode(value.to_bytes(length, "big")).rstrip(b"=").decode("ascii")


def main() -> None:
    private_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    public_numbers = private_key.public_key().public_numbers()

    jwks = {
        "keys": [
            {
                "kty": "RSA",
                "use": "sig",
                "alg": "RS256",
                "kid": _KID,
                "n": _b64url_uint(public_numbers.n),
                "e": _b64url_uint(public_numbers.e),
            }
        ]
    }
    os.makedirs(_JWKS_DIR, exist_ok=True)
    with open(_JWKS_PATH, "w", encoding="utf-8") as handle:
        json.dump(jwks, handle)

    now = int(time.time())
    claims = {
        "sub": f"svc-orchestrator-{uuid.uuid4()}",
        "iat": now,
        "nbf": now,
        "exp": now + _TTL_SECONDS,
        # The engines/scorer gate on the INVESTIGATOR role (Req 19.7 / 22.6).
        "roles": ["INVESTIGATOR"],
    }
    private_pem = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    ).decode("ascii")
    # Persist the signing key (0600, gitignored) for mint-token.py.
    with open(_KEY_PATH, "w", encoding="utf-8") as handle:
        handle.write(private_pem)
    os.chmod(_KEY_PATH, 0o600)
    token = jwt.encode(claims, private_pem, algorithm="RS256", headers={"kid": _KID})

    with open(_ENV_PATH, "w", encoding="utf-8") as handle:
        handle.write("# LOCAL DEV ONLY — generated by scripts/dev/gen-service-token.py.\n")
        handle.write("# Gitignored. Regenerate before `podman-compose up`.\n")
        # The orchestrator presents this on internal engine/scorer calls.
        handle.write(f"ORCHESTRATOR_SERVICE_TOKEN={token}\n")
        # The History Inconsistency + Regional Analysis engines present the same
        # INVESTIGATOR credential on their internal adapter calls (CRA, Stats
        # Canada, Job Bank), which validate a GCKey Bearer on every endpoint
        # (Req 19.7). They read it from SERVICE_TOKEN.
        handle.write(f"SERVICE_TOKEN={token}\n")

    print(f"Wrote JWKS  -> {os.path.relpath(_JWKS_PATH, _REPO_ROOT)}")
    print(f"Wrote key   -> {os.path.relpath(_KEY_PATH, _REPO_ROOT)} (for mint-token.py)")
    print(f"Wrote token -> {os.path.relpath(_ENV_PATH, _REPO_ROOT)} "
          f"(INVESTIGATOR, ttl={_TTL_SECONDS}s)")


if __name__ == "__main__":
    main()
